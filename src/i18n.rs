//! 多语言支持：目前支持中文与英文。
//!
//! 界面文案全部通过 [`Strings`] 按语言查找；首次启动（无持久化配置）时根据
//! 系统语言决定默认语言：中文环境用中文，其他环境一律用英文。

use serde::{Deserialize, Serialize};

/// 界面语言。
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default, Serialize, Deserialize)]
pub enum Language {
    #[serde(rename = "zh")]
    Chinese,
    #[serde(rename = "en")]
    #[default]
    English,
}

impl Language {
    /// 当前语言的界面文案。
    pub fn strings(self) -> &'static Strings {
        match self {
            Self::Chinese => &ZH,
            Self::English => &EN,
        }
    }

    /// 语言菜单中显示的名称。
    pub fn label(self) -> &'static str {
        match self {
            Self::Chinese => "中文",
            Self::English => "English",
        }
    }

    /// 根据系统语言决定默认语言：中文环境返回中文，其余一律英文。
    pub fn system() -> Self {
        match sys_locale::get_locale() {
            Some(locale) if locale.to_ascii_lowercase().starts_with("zh") => Self::Chinese,
            _ => Self::English,
        }
    }
}

