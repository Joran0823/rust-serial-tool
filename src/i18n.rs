impl Strings {
    /// 将模板中的 `{key}` 占位符替换为给定值（`format!` 需要字面量，动态模板走这里）。
    pub fn fill(&self, template: &'static str, args: &[(&str, String)]) -> String {
        let mut out = template.to_string();
        for (key, value) in args {
            out = out.replace(&format!("{{{key}}}"), value);
        }
        out
    }
}

