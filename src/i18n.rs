#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn system_language_prefers_chinese_only_for_zh_locales() {
        // 无法注入系统环境，仅验证 zh 前缀判定逻辑的等价条件
        assert!(Language::Chinese.strings().app_title.contains("串口"));
        assert!(Language::English.strings().app_title.contains("Serial"));
    }

    #[test]
    fn both_languages_cover_same_keys() {
        // 结构体字段即键集合，两套常量字段数量一致即覆盖一致；
        // 再抽查关键文案非空。
        let zh = Language::Chinese.strings();
        let en = Language::English.strings();
        assert!(!zh.open_port.is_empty() && !en.open_port.is_empty());
        assert!(!zh.select_all.is_empty() && !en.select_all.is_empty());
    }
}
